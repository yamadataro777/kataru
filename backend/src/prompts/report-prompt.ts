export function buildFreeReportPrompt(transcript: string, freeSessionsUsed: number = 0): string {
  const isTrialPeriod = freeSessionsUsed < 3;

  const questionsSchema = isTrialPeriod
    ? `"deep_questions": [
    {
      "question": "思考を揺さぶる問い",
      "context": "なぜこの問いが重要か。ユーザーのどの発言から導かれたか",
      "angle": "この問いが開く予想外の視点"
    }
  ]`
    : `"exploration_questions": ["2-3個の問い"]`;

  const questionsRules = isTrialPeriod
    ? `## 深い問いの生成ルール:
- 3-5個の問いを生成
- 各問いは以下のいずれかの機能を持つ:
  1. 前提転覆型: 無意識の前提を明示し「もしそれが違ったら？」と問う
  2. 構造発見型: 複数の発言を横断して本人が気づいていないパターンを問う
  3. 越境接続型: 全く別の領域のフレームワークで捉え直す
  4. 逆説提示型: 結論と矛盾する仮説を提示し検証を促す
  5. 時間軸転換型: 異なる時間スケールから再評価させる
- 「context」にはユーザーの具体的発言を引用
- 「angle」は1文で新しい視点を明示
- 並び順: 最も思考の運動量が大きい問いを最後に（クライマックス構造）
- 禁止: 褒め言葉、情報を求める質問（思考を求める質問のみ）`
    : `## 問いの生成ルール:
- ユーザーの具体的な発言内容に基づく問いであること
- 「〜についてもっと教えてください」のような単なる深掘りは禁止
- 以下のタイプから選ぶ:
  - 暗黙の前提を問う（「〜を前提にしているが、もし〜だとしたら？」）
  - 対立する視点を提示する（「逆の立場の人は何と言うか？」）
  - 具体と抽象を行き来させる
  - 時間軸をずらす（「5年後に振り返ったとき、今の判断をどう評価するか？」）
- 答えが一言で終わらない問いであること
- 褒め言葉・フラッタリー禁止`;

  return `あなたは音声トランスクリプトを分析する専門家です。
ユーザーは声で自分の考えを話しました。以下の文字起こしを分析し、思考の整理を助けるレポートを生成してください。

## 重要なルール:
- ユーザーの具体的な発言を踏まえること。一般論は禁止。
- 「〜が重要です」「〜を検討しましょう」のような空虚な文は禁止。
- フィラー（えーと、あのー、まあ）は無視すること。
- 繰り返しは1回にまとめること。
- すべての出力は日本語で書くこと。
- ユーザーが実際に話した内容だけを分析すること。話していないことを捏造しないこと。

${questionsRules}

## トランスクリプト:
${transcript}

## 出力形式 (JSON):
{
  "title": "セッションの核心を一言で表すタイトル",
  "summary": "このセッションで何を考え、何が見えてきたかの要約（2-3文）",
  "key_insights": ["ユーザーの発言から読み取れる重要な気づき3個。必ずユーザーの具体的な発言内容に基づくこと"],
  "topics": ["議論の中心にあったテーマ2-5個"],
  "sentiment": {
    "overall": "positive/neutral/negative",
    "score": 0.0-1.0,
    "details": "感情の背景と推移の説明"
  },
  ${questionsSchema},
  "blockage": "いま何が詰まっているか（1文。ユーザーの発言を踏まえた具体的な記述）",
  "discussion_points": ["論点1", "論点2", "論点3"],
  "next_step": "次にやること（10-20分で完了する具体的アクション1つ）"
}

## blockage / discussion_points / next_step のルール:
- blockage: ユーザーの発言から導出した1文。「〜が決まらず〜している」形式。
- discussion_points: 必ず3つ。各項目は1文で完結。
- next_step: 「人生の優先順位を見直す」のような抽象は禁止。「今週やらないことを3つ書く」レベルの具体性。10-20分で完了する具体的アクション1つ。

JSONのみを出力してください。マークダウンのコードブロックは使わないでください。`;
}

